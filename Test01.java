public class Test01 {
    public static void main(String[] args) {
       //输出恐龙的信息:霸王龙 8岁 11.5 公斤
        System.out.println("恐龙的信息:霸王龙 8岁 11.5 公斤");
        //输出恐龙的名字
        System.out.println("霸王龙");
        //输出恐龙的年龄
        System.out.println("8岁");
        //输出恐龙的重量
        System.out.println("11.5 公斤");     
        //输出恐龙的性别 内容只能有一个字
        System.out.println('公');
    }
}
